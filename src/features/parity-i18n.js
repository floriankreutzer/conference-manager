function interpolate(template, values) {
  return String(template).replace(/\{(\w+)\}/g, (_match, key) => String(values[key] ?? ''));
}

export function ptFor(targetLanguage, key, values = {}) {
  const current = MESSAGES[targetLanguage] || MESSAGES.de;
  const fallback = MESSAGES.de[key] || key;
  return interpolate(current[key] || fallback, values);
}

export function pt(key, values = {}) {
  return ptFor(language(), key, values);
}

export function parityLocale() {
  return language() === 'en' ? 'en-GB' : 'de-DE';
}
