export function uxText(key, values = {}) {
  const lang = language() === 'en' ? 'en' : 'de';
  const template = COPY[lang][key] || COPY.de[key] || key;
  return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, token) => String(values[token] ?? `{${token}}`));
}
